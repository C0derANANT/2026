// Operators In C
#include <stdio.h>
#include <math.h>
int main() {
    int a = 2, b = 5;
    int Addition = a + b;  // Addition Operator
    int Subtraction = a - b;  // Subtraction Operator
    int Multiplication = a * b;  // Multiplication Operator
    int Division = b / a;  // Division Operator Or Floor Division Operator
    int Modulus = b % a;  // Modulus Operator
    int Exponential = pow(a, b);  // Exponential Operator
    printf("Addition: %d\n", Addition);
    printf("Subtraction: %d\n", Subtraction);
    printf("Multiplication: %d\n", Multiplication);
    printf("Division: %d\n", Division);
    printf("Modulus: %d\n", Modulus);
    printf("Exponential: %d\n", Exponential);
    return 0;
} 